--------------------------------------------------------------------------------
-- CLYVO VET - ChallengeAPI
-- script_bd.sql
--
-- DDL + carga inicial de dados do banco de dados Oracle utilizado pela solucao.
-- Reflete exatamente o schema gerado pelas EF Core Migrations do projeto
-- (Migrations/20260512192211_InitialCreate.cs), com comentarios adicionados
-- para documentacao (requisito da Entrega - 3o Sprint / DevOps Tools & Cloud
-- Computing, item 3.3).
--
-- Tabelas representam o CORE do negocio da CLYVO VET (jornada de saude do pet):
--   TUTORES   -> donos dos pets
--   PETS      -> animais cadastrados, vinculados a um tutor
--   VACINAS   -> vacinas aplicadas em cada pet
--   CONSULTAS -> consultas veterinarias realizadas em cada pet
--
-- Ordem de execucao: TUTORES -> PETS -> VACINAS / CONSULTAS (respeita as FKs)
--
-- Este script roda tanto manualmente via sqlplus quanto automaticamente na
-- primeira inicializacao do container Oracle (ver docker/Dockerfile.oracle,
-- que o copia para /container-entrypoint-initdb.d/). Nesse caso a imagem
-- gvenzl/oracle-xe executa o arquivo como usuario SYS - por isso o primeiro
-- comando troca o schema atual para SYSTEM, que e o usuario usado pela API
-- na connection string (User Id=system).
--------------------------------------------------------------------------------
ALTER SESSION SET CURRENT_SCHEMA = SYSTEM;

--------------------------------------------------------------------------------
