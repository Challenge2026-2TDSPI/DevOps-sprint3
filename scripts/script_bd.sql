--------------------------------------------------------------------------------
-- 2. TABELA: TUTORES
--------------------------------------------------------------------------------
CREATE TABLE "Tutores" (
    "Id"       NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    "Nome"     NVARCHAR2(2000) NOT NULL,
    "Telefone" NVARCHAR2(2000) NOT NULL,
    "Email"    NVARCHAR2(2000) NOT NULL,
    CONSTRAINT "PK_Tutores" PRIMARY KEY ("Id")
);

COMMENT ON TABLE "Tutores" IS 'Donos/responsaveis pelos pets cadastrados na CLYVO VET';
COMMENT ON COLUMN "Tutores"."Id" IS 'Identificador unico do tutor (PK)';
COMMENT ON COLUMN "Tutores"."Nome" IS 'Nome completo do tutor';
COMMENT ON COLUMN "Tutores"."Telefone" IS 'Telefone de contato do tutor';
COMMENT ON COLUMN "Tutores"."Email" IS 'E-mail de contato do tutor';

--------------------------------------------------------------------------------
-- 3. TABELA: PETS
--------------------------------------------------------------------------------
CREATE TABLE "Pets" (
    "Id"        NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    "Nome"      NVARCHAR2(2000) NOT NULL,
    "Especie"   NVARCHAR2(2000) NOT NULL,
    "Raca"      NVARCHAR2(2000) NOT NULL,
    "Idade"     NUMBER(10)      NOT NULL,
    "TutorId"   NUMBER(10)      NOT NULL,
    "ClinicaId" NUMBER(10)      NOT NULL,
    CONSTRAINT "PK_Pets" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Pets_Tutores_TutorId" FOREIGN KEY ("TutorId")
        REFERENCES "Tutores" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_Pets_TutorId" ON "Pets" ("TutorId");

COMMENT ON TABLE "Pets" IS 'Pets cadastrados, cada um vinculado a um tutor';
COMMENT ON COLUMN "Pets"."Id" IS 'Identificador unico do pet (PK)';
COMMENT ON COLUMN "Pets"."Nome" IS 'Nome do pet';
COMMENT ON COLUMN "Pets"."Especie" IS 'Especie do pet (ex: Cao, Gato)';
COMMENT ON COLUMN "Pets"."Raca" IS 'Raca do pet';
COMMENT ON COLUMN "Pets"."Idade" IS 'Idade do pet, em anos';
COMMENT ON COLUMN "Pets"."TutorId" IS 'FK para Tutores.Id - tutor responsavel pelo pet';
COMMENT ON COLUMN "Pets"."ClinicaId" IS 'Identificador da clinica CLYVO VET responsavel pelo atendimento do pet';

--------------------------------------------------------------------------------
-- 4. TABELA: VACINAS
--------------------------------------------------------------------------------
CREATE TABLE "Vacinas" (
    "Id"             NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    "NomeVacina"     NVARCHAR2(2000) NOT NULL,
    "DataAplicacao"  NVARCHAR2(2000) NOT NULL,
    "ProximaDose"    NVARCHAR2(2000) NOT NULL,
    "PetId"          NUMBER(10)      NOT NULL,
    CONSTRAINT "PK_Vacinas" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Vacinas_Pets_PetId" FOREIGN KEY ("PetId")
        REFERENCES "Pets" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_Vacinas_PetId" ON "Vacinas" ("PetId");

COMMENT ON TABLE "Vacinas" IS 'Vacinas aplicadas em cada pet, com previsao da proxima dose';
COMMENT ON COLUMN "Vacinas"."Id" IS 'Identificador unico da vacina aplicada (PK)';
COMMENT ON COLUMN "Vacinas"."NomeVacina" IS 'Nome/tipo da vacina aplicada';
COMMENT ON COLUMN "Vacinas"."DataAplicacao" IS 'Data em que a vacina foi aplicada';
COMMENT ON COLUMN "Vacinas"."ProximaDose" IS 'Data prevista para a proxima dose/reforco';
COMMENT ON COLUMN "Vacinas"."PetId" IS 'FK para Pets.Id - pet que recebeu a vacina';

--------------------------------------------------------------------------------
-- 5. TABELA: CONSULTAS
--------------------------------------------------------------------------------
CREATE TABLE "Consultas" (
    "Id"            NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    "DataConsulta"  NVARCHAR2(2000) NOT NULL,
    "Descricao"     NVARCHAR2(2000) NOT NULL,
    "Veterinario"   NVARCHAR2(2000) NOT NULL,
    "PetId"         NUMBER(10)      NOT NULL,
    CONSTRAINT "PK_Consultas" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Consultas_Pets_PetId" FOREIGN KEY ("PetId")
        REFERENCES "Pets" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_Consultas_PetId" ON "Consultas" ("PetId");

COMMENT ON TABLE "Consultas" IS 'Consultas veterinarias realizadas para cada pet';
COMMENT ON COLUMN "Consultas"."Id" IS 'Identificador unico da consulta (PK)';
COMMENT ON COLUMN "Consultas"."DataConsulta" IS 'Data em que a consulta foi realizada';
COMMENT ON COLUMN "Consultas"."Descricao" IS 'Descricao/motivo da consulta';
COMMENT ON COLUMN "Consultas"."Veterinario" IS 'Nome do veterinario responsavel pelo atendimento';
COMMENT ON COLUMN "Consultas"."PetId" IS 'FK para Pets.Id - pet atendido na consulta';

